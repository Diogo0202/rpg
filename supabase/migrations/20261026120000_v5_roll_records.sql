-- V5-07: authenticated V5 rolls stored per character, with one Willpower reroll.
-- Dice are generated inside the database so a client cannot forge results;
-- clients have no direct write privilege on the table, only the two RPCs.
-- Campaign members read the history; the author (owner or campaign manager of
-- the sheet) writes it. Only the newest rolls per sheet are kept.

create table public.v5_roll_records (
  id uuid primary key default gen_random_uuid(),
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  sheet_id uuid not null references public.character_sheets(id) on delete cascade,
  author_id uuid references auth.users(id) on delete set null,
  pool integer not null check (pool between 1 and 30),
  hunger integer not null check (hunger between 0 and 5 and hunger <= pool),
  difficulty integer not null check (difficulty between 1 and 100),
  normal_dice integer[] not null,
  hunger_dice integer[] not null,
  outcome jsonb not null check (jsonb_typeof(outcome) = 'object'),
  details jsonb not null default '{}' check (jsonb_typeof(details) = 'object' and pg_column_size(details) <= 8192),
  original_normal_dice integer[],
  rerolled_indices integer[],
  willpower_event_id bigint references public.character_sheet_events(id) on delete set null,
  created_at timestamptz not null default clock_timestamp(),
  rerolled_at timestamptz,
  check (coalesce(cardinality(normal_dice), 0) + coalesce(cardinality(hunger_dice), 0) = pool),
  check (coalesce(cardinality(hunger_dice), 0) = hunger),
  check ((rerolled_at is null) = (original_normal_dice is null)
     and (rerolled_at is null) = (rerolled_indices is null)),
  check (rerolled_indices is null or cardinality(rerolled_indices) between 1 and 3)
);
create index v5_roll_records_sheet_idx on public.v5_roll_records (sheet_id, created_at desc, id desc);
alter table public.v5_roll_records enable row level security;
revoke all on public.v5_roll_records from anon, authenticated;
grant select on public.v5_roll_records to authenticated;
create policy "campaign members read v5 rolls"
  on public.v5_roll_records for select to authenticated
  using (private.is_campaign_member(campaign_id));

comment on table public.v5_roll_records is
  'V5 rolls generated by record_v5_roll; at most one Willpower reroll each (reroll_v5_roll). Newest 50 per sheet are kept.';

-- One d10 from pg_strong_random (gen_random_uuid): the first 8 hex digits of a
-- v4 UUID are random. Rejection sampling keeps the faces uniform.
create or replace function private.v5_random_die()
returns integer
language plpgsql
volatile
security invoker
set search_path = pg_catalog
as $$
declare
  value bigint;
begin
  loop
    value := ('x' || substr(gen_random_uuid()::text, 1, 8))::bit(32)::bigint;
    if value < 0 then value := value + 4294967296; end if;
    if value < 4294967290 then return (value % 10)::integer + 1; end if;
  end loop;
end;
$$;
revoke all on function private.v5_random_die() from public;

create or replace function private.v5_roll_outcome(p_normal integer[], p_hunger integer[], p_difficulty integer)
returns jsonb
language sql
immutable
security invoker
set search_path = pg_catalog
as $$
  with faces as (
    select face, false as hunger from unnest(coalesce(p_normal, '{}'::integer[])) as face
    union all
    select face, true from unnest(coalesce(p_hunger, '{}'::integer[])) as face
  ), counts as (
    select count(*) filter (where face >= 6) as successes,
           count(*) filter (where face = 10) as tens,
           count(*) filter (where face = 10 and hunger) as hunger_tens,
           count(*) filter (where face = 1 and hunger) as hunger_ones
      from faces
  ), totals as (
    select *, successes + 2 * (tens / 2) as total, tens / 2 as pairs from counts
  )
  select jsonb_build_object(
    'successes', total,
    'success', total >= p_difficulty,
    'critical_pairs', pairs,
    'messy_critical', total >= p_difficulty and pairs > 0 and hunger_tens > 0,
    'clean_critical', total >= p_difficulty and pairs > 0 and hunger_tens = 0,
    'bestial_failure', total < p_difficulty and hunger_ones > 0
  ) from totals;
$$;
revoke all on function private.v5_roll_outcome(integer[], integer[], integer) from public;
grant execute on function private.v5_roll_outcome(integer[], integer[], integer) to authenticated;

create or replace function private.can_write_sheet(p_sheet public.character_sheets)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, private, auth
as $$
  select auth.uid() is not null
     and (p_sheet.owner_id = auth.uid() or private.can_manage_campaign(p_sheet.campaign_id));
$$;
revoke all on function private.can_write_sheet(public.character_sheets) from public;

create or replace function public.record_v5_roll(
  p_sheet_id uuid, p_pool integer, p_hunger integer, p_difficulty integer, p_details jsonb default '{}'
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, private, auth
as $$
declare
  sheet public.character_sheets;
  normal_dice integer[] := '{}';
  hunger_dice integer[] := '{}';
  saved public.v5_roll_records;
begin
  if auth.uid() is null then raise exception 'session required' using errcode = '42501'; end if;
  if p_pool is null or p_pool not between 1 and 30 or p_hunger is null or p_hunger not between 0 and 5
     or p_hunger > p_pool or p_difficulty is null or p_difficulty not between 1 and 100 then
    raise exception 'invalid pool, hunger or difficulty' using errcode = '22023';
  end if;
  if p_details is null or jsonb_typeof(p_details) <> 'object' or pg_column_size(p_details) > 8192 then
    raise exception 'details must be a small object' using errcode = '22023';
  end if;
  select * into sheet from public.character_sheets where id = p_sheet_id;
  if not found or not private.can_write_sheet(sheet) then
    raise exception 'sheet not found or not writable' using errcode = '42501';
  end if;
  for i in 1 .. p_pool - p_hunger loop normal_dice := normal_dice || private.v5_random_die(); end loop;
  for i in 1 .. p_hunger loop hunger_dice := hunger_dice || private.v5_random_die(); end loop;
  insert into public.v5_roll_records
    (campaign_id, sheet_id, author_id, pool, hunger, difficulty, normal_dice, hunger_dice, outcome, details)
  values
    (sheet.campaign_id, sheet.id, auth.uid(), p_pool, p_hunger, p_difficulty, normal_dice, hunger_dice,
     private.v5_roll_outcome(normal_dice, hunger_dice, p_difficulty), p_details)
  returning * into saved;
  -- Retention: keep the newest 50 rolls of this character.
  delete from public.v5_roll_records old
   where old.sheet_id = sheet.id
     and old.id not in (
       select keep.id from public.v5_roll_records keep
        where keep.sheet_id = sheet.id
        order by keep.created_at desc, keep.id desc
        limit 50);
  return to_jsonb(saved);
end;
$$;
revoke all on function public.record_v5_roll(uuid, integer, integer, integer, jsonb) from public, anon;
grant execute on function public.record_v5_roll(uuid, integer, integer, integer, jsonb) to authenticated;

-- Rerolls up to three ordinary dice (never Hunger dice) once per roll and
-- spends one Willpower in the same transaction: through spend_meta_currency
-- when the template declares a 'vontade' currency (track: superficial damage,
-- pool: current points), else through adjust_sheet_number on a plain
-- 'vontade_superficial' field. Any failure rolls the whole reroll back.
create or replace function public.reroll_v5_roll(p_roll_id uuid, p_indices integer[])
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, private, auth
as $$
declare
  roll public.v5_roll_records;
  sheet public.character_sheets;
  template_schema jsonb;
  currency jsonb;
  new_dice integer[];
  idx integer;
  spend jsonb;
  willpower_max numeric;
  damage numeric;
  event_id bigint;
begin
  if auth.uid() is null then raise exception 'session required' using errcode = '42501'; end if;
  select * into roll from public.v5_roll_records where id = p_roll_id for update;
  if not found or roll.author_id is distinct from auth.uid() then
    raise exception 'roll not found or not yours' using errcode = '42501';
  end if;
  if roll.rerolled_at is not null then
    raise exception 'this roll was already rerolled with Willpower' using errcode = '23505';
  end if;
  if p_indices is null or cardinality(p_indices) not between 1 and 3
     or (select count(distinct value) from unnest(p_indices) as value) <> cardinality(p_indices)
     or exists (select 1 from unnest(p_indices) as value
                 where value is null or value < 0 or value >= coalesce(cardinality(roll.normal_dice), 0)) then
    raise exception 'choose from one to three distinct ordinary dice' using errcode = '22023';
  end if;
  select * into sheet from public.character_sheets where id = roll.sheet_id for update;
  if not found or not private.can_write_sheet(sheet) then
    raise exception 'sheet not found or not writable' using errcode = '42501';
  end if;

  select schema into template_schema from public.system_templates
   where id = sheet.template_id and campaign_id = sheet.campaign_id;
  select value into currency
    from jsonb_array_elements(coalesce(template_schema -> 'meta_currencies', '[]'::jsonb))
   where value ->> 'id' = 'vontade' limit 1;
  if currency is not null and currency ->> 'mode' = 'track' then
    -- A full Willpower track cannot pay for a reroll.
    willpower_max := case
      when jsonb_typeof(currency -> 'max') = 'number' then (currency ->> 'max')::numeric
      when jsonb_typeof(sheet.values -> coalesce(currency ->> 'max_field', 'vontade_max')) = 'number'
        then (sheet.values ->> coalesce(currency ->> 'max_field', 'vontade_max'))::numeric
      when jsonb_typeof(sheet.values -> 'autocontrole') = 'number' and jsonb_typeof(sheet.values -> 'resolucao') = 'number'
        then (sheet.values ->> 'autocontrole')::numeric + (sheet.values ->> 'resolucao')::numeric
    end;
    damage := coalesce(case when jsonb_typeof(sheet.values -> (currency ->> 'field')) = 'number'
                            then (sheet.values ->> (currency ->> 'field'))::numeric end, 0)
            + coalesce(case when jsonb_typeof(sheet.values -> 'vontade_agravada') = 'number'
                            then (sheet.values ->> 'vontade_agravada')::numeric end, 0);
    if willpower_max is not null and damage + 1 > willpower_max then
      raise exception 'Willpower track is full' using errcode = '23514';
    end if;
  end if;

  new_dice := roll.normal_dice;
  foreach idx in array p_indices loop
    new_dice[idx + 1] := private.v5_random_die();
  end loop;
  update public.v5_roll_records
     set original_normal_dice = roll.normal_dice,
         normal_dice = new_dice,
         rerolled_indices = (select array_agg(value order by value) from unnest(p_indices) as value),
         outcome = private.v5_roll_outcome(new_dice, roll.hunger_dice, roll.difficulty),
         rerolled_at = now()
   where id = roll.id
  returning * into roll;

  if currency is not null then
    spend := public.spend_meta_currency(sheet.id, 'vontade', 1, 'Rerrolagem de Vontade (V5)');
  elsif exists (select 1 from jsonb_array_elements(coalesce(template_schema -> 'fields', '[]'::jsonb)) as fields(field)
                 where field ->> 'id' = 'vontade_superficial' and field ->> 'kind' = 'number') then
    spend := public.adjust_sheet_number(sheet.id, 'vontade_superficial', 1, 'Rerrolagem de Vontade (V5)');
  end if;
  if spend is not null then
    event_id := (spend -> 'event' ->> 'id')::bigint;
    update public.v5_roll_records set willpower_event_id = event_id where id = roll.id returning * into roll;
  end if;
  return jsonb_build_object(
    'roll', to_jsonb(roll),
    'willpower_spent', spend is not null,
    'sheet_values', case when spend is not null then spend -> 'sheet' -> 'values' end
  );
end;
$$;
revoke all on function public.reroll_v5_roll(uuid, integer[]) from public, anon;
grant execute on function public.reroll_v5_roll(uuid, integer[]) to authenticated;
